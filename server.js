/** GET /health : proves the server and database both respond. */
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "ok" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", database: "unreachable", message: "Database check failed." });
  }
});

app.use("/api/records", require("./routes/records"));

// Unknown routes: JSON 404.
app.use((req, res) => {
  res.status(404).json({ message: `Route ${req.method} ${req.path} does not exist.` });
});

// Error middleware (four parameters). Details are logged; the client gets a clear message.
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed") {
    return res.status(400).json({ message: "Malformed JSON in request body." });
  }
  if (error.status && error.status < 500) {
    return res.status(error.status).json({ message: error.message });
  }
  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Unexpected server error." });
});

/** Create the table on first run and seed it once, only when the table is brand new. */
async function initDatabase() {
  const existing = await pool.query("SELECT to_regclass('public.records') AS name");
  const read = (file) => fs.readFileSync(path.join(__dirname, file), "utf8");
  await pool.query(read("schema.sql"));
  if (!existing.rows[0].name) {
    await pool.query(read("seed.sql"));
    console.log("Created records table and inserted starting records.");
  }
}

const port = process.env.PORT || 3000;

initDatabase()
  .catch((error) => console.error("Database setup failed:", error.message))
  .finally(() => {
    app.listen(port, "0.0.0.0", () => console.log(`Server listening on port ${port}`));
  });
